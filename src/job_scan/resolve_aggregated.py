"""Promote boards that aggregators keep surfacing into a generated sweep list.

LinkedIn, freehire and HN link to Greenhouse/Lever/Ashby boards we don't scan.
Scanning those boards directly gets liveness (aggregator rows are never marked
gone; measured 2026-11-07: 452 of 872 open aggregator rows on 237 such boards
were already off their board) and the board's full description. Earlier sight
is small: median aggregator lag behind the ATS publish date was 0.8 days.

A board is kept when any of its rows scored 85+ or was applied to, its slug
came from a posting URL (a slug found only in description text can be another
company's link), no blocked company owns it, it isn't already in companies.yaml
or the no-whiteboard list, and its API returns a posting. Boards already in
the generated file stay candidates: once scanned, their rows are re-keyed to
the board's fingerprint and no longer look like aggregator rows.

Written to config/companies.auto.yaml; refreshed by weekly.sh, scanned daily.
"""
from __future__ import annotations

import logging
import sqlite3
from collections import Counter, defaultdict
from dataclasses import dataclass, field

from .config import CONFIG_DIR, Filters, load_auto_companies, load_companies, load_no_whiteboard_companies
from .filter import _blocked_company_re
from .resolve_companies import _validate, detect

log = logging.getLogger(__name__)

OUT = CONFIG_DIR / "companies.auto.yaml"
BOARD_ATS = ("greenhouse", "lever", "ashby")
APPLIED = ("applied", "interview", "offer", "rejected", "no_response")
MIN_SCORE = 85
# Greenhouse/Lever/Ashby hosts drop boards under heavy concurrency
# (career-ops saw Lever lose ~2,400 boards at 20).
MAX_WORKERS = 6


@dataclass
class _Board:
    names: Counter[str] = field(default_factory=Counter)
    strong: int = 0
    applied: int = 0


def _board_of(fingerprint: str, url: str) -> tuple[str, str] | None:
    ats, _, rest = fingerprint.partition(":")
    if ats in BOARD_ATS:
        return ats, rest.partition(":")[0].lower()
    hit = detect(url or "")
    if hit and hit["ats"] in BOARD_ATS:
        return hit["ats"], hit["slug"].lower()
    return None


def resolve_aggregated(con: sqlite3.Connection, filters: Filters) -> list[dict]:
    boards: dict[tuple[str, str], _Board] = defaultdict(_Board)
    from_aggregator: set[tuple[str, str]] = set()
    for r in con.execute("SELECT fingerprint, url, company, score, status, applied_at FROM postings"):
        key = _board_of(r["fingerprint"], r["url"])
        if key is None:
            continue
        b = boards[key]
        b.names[r["company"]] += 1
        b.strong += (r["score"] or 0) >= MIN_SCORE
        b.applied += bool(r["status"] in APPLIED or r["applied_at"])
        if not r["fingerprint"].startswith(BOARD_ATS):
            from_aggregator.add(key)

    curated = {(c.ats, c.slug.lower()) for c in load_companies() + load_no_whiteboard_companies()}
    candidates = (from_aggregator | {(c.ats, c.slug.lower()) for c in load_auto_companies()}) - curated
    blocked = _blocked_company_re(tuple(filters.blocked_companies)) if filters.blocked_companies else None

    keep: list[dict] = []
    for ats, slug in sorted(candidates):
        b = boards.get((ats, slug))
        if b is None or not (b.strong or b.applied):
            continue
        name = (b.names.most_common(1)[0][0] or "").strip()
        if blocked and any(blocked.search(n or "") for n in b.names):
            continue
        keep.append({"name": name, "ats": ats, "slug": slug})
    log.info("%d candidate boards (%d from aggregator rows), %d qualify; validating ...",
             len(candidates), len(from_aggregator - curated), len(keep))
    return _validate(keep, MAX_WORKERS)


def write_yaml(companies: list[dict]) -> str:
    import yaml
    companies = sorted(companies, key=lambda c: c["name"].lower())
    header = (
        "# Auto-generated by `job-scan resolve-agg` (weekly.sh); do not edit.\n"
        "# Greenhouse/Lever/Ashby boards that aggregators surfaced with a posting\n"
        "# at 85+ or an application. Hand-picked boards go in companies.yaml.\n"
    )
    OUT.write_text(header + yaml.safe_dump({"companies": companies}, sort_keys=False))
    return str(OUT)
